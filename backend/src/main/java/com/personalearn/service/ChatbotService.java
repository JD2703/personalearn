package com.personalearn.service;

import com.fasterxml.jackson.databind.JsonNode;
import com.fasterxml.jackson.databind.ObjectMapper;
import com.personalearn.dto.Dtos.*;
import com.personalearn.model.ChatMessage;
import com.personalearn.model.User;
import com.personalearn.repository.ChatMessageRepository;
import com.personalearn.repository.UserRepository;
import org.slf4j.Logger;
import org.slf4j.LoggerFactory;
import org.springframework.beans.factory.annotation.Value;
import org.springframework.stereotype.Service;
import org.springframework.transaction.annotation.Transactional;

import java.net.URI;
import java.net.http.HttpClient;
import java.net.http.HttpRequest;
import java.net.http.HttpResponse;
import java.time.Duration;
import java.util.*;

/**
 * "Persona" — the AI learning companion.
 *
 * If ANTHROPIC_API_KEY is configured, replies are generated by Claude with the learner's MBTI profile,
 * progress and recommendations injected as context. Otherwise a built-in intent-based tutor answers,
 * still fully personalised to the learner's personality type and progress.
 */
@Service
public class ChatbotService {

    private static final Logger log = LoggerFactory.getLogger(ChatbotService.class);

    private final ChatMessageRepository messages;
    private final UserRepository users;
    private final MbtiService mbti;
    private final ProgressService progress;
    private final ObjectMapper json = new ObjectMapper();
    private final HttpClient http = HttpClient.newBuilder().connectTimeout(Duration.ofSeconds(10)).build();
    private final String apiKey;
    private final String model;

    public ChatbotService(ChatMessageRepository messages, UserRepository users, MbtiService mbti,
                          ProgressService progress,
                          @Value("${app.ai.anthropic-api-key:}") String apiKey,
                          @Value("${app.ai.model}") String model) {
        this.messages = messages;
        this.users = users;
        this.mbti = mbti;
        this.progress = progress;
        this.apiKey = apiKey;
        this.model = model;
    }

    @Transactional(readOnly = true)
    public List<ChatMessageDto> history(Long userId) {
        List<ChatMessage> list = new ArrayList<>(messages.findTop50ByUserIdOrderByCreatedAtDesc(userId));
        Collections.reverse(list);
        return list.stream().map(m -> new ChatMessageDto(m.getId(), m.getSender(), m.getContent(), m.getCreatedAt(), null)).toList();
    }

    @Transactional
    public void clear(Long userId) {
        messages.deleteByUserId(userId);
    }

    @Transactional
    public ChatMessageDto chat(Long userId, String text) {
        User user = users.findById(userId).orElseThrow();
        messages.save(new ChatMessage(user, "user", text.trim()));

        DashboardDto dash = progress.dashboard(userId);
        Reply reply = null;
        if (apiKey != null && !apiKey.isBlank()) {
            reply = askClaude(user, dash, text);
        }
        if (reply == null) {
            reply = ruleBased(user, dash, text);
        }
        String botText = reply.text().length() > 3990 ? reply.text().substring(0, 3990) + "…" : reply.text();
        ChatMessage saved = messages.save(new ChatMessage(user, "bot", botText));
        return new ChatMessageDto(saved.getId(), "bot", saved.getContent(), saved.getCreatedAt(), reply.suggestions());
    }

    private record Reply(String text, List<String> suggestions) {}

    // ------------------------------------------------------------------ rule-based tutor

    private Reply ruleBased(User user, DashboardDto dash, String raw) {
        String q = raw.toLowerCase(Locale.ROOT);
        String type = user.getMbtiType();
        String first = user.getName().split(" ")[0];
        List<String> defaults = List.of("What should I learn next?", "How should I study?", "How am I doing?");

        if (type == null) {
            return new Reply("Hi " + first + "! I personalise everything to your personality, but I don't know your MBTI type yet. "
                    + "Take the 2-minute personality quiz from the menu and I'll tailor courses, study tips and lesson formats to you.",
                    List.of("What is MBTI?", "Why does personality matter for learning?"));
        }
        MbtiService.TypeProfile p = mbti.profile(type);

        if (q.length() < 25 && (matches(q, "hello", "hey", "good morning", "good evening") || q.matches("^(hi|hii+|yo)\\b.*"))) {
            return new Reply("Hey " + first + "! 👋 I'm Persona, your learning companion. As an " + type + " — " + p.nickname()
                    + " — you're a " + p.learningStyle().toLowerCase() + " What would you like to work on today?", defaults);
        }
        if (matches(q, "recommend", "what should i learn", "next course", "suggest", "which course")) {
            if (dash.recommendations().isEmpty()) {
                return new Reply("You're enrolled in every course we have — impressive! Focus on finishing the ones in progress.", defaults);
            }
            StringBuilder sb = new StringBuilder("Based on your " + type + " profile and progress, here are my top picks:\n");
            dash.recommendations().stream().limit(3).forEach(r -> sb.append("\n• **").append(r.course().title())
                    .append("** (").append(r.matchPercent()).append("% match) — ").append(r.reasons().get(0)));
            sb.append("\n\nOpen any of them from your dashboard to enrol.");
            return new Reply(sb.toString(), List.of("Why that first course?", "How should I study?", "How am I doing?"));
        }
        if (matches(q, "progress", "how am i doing", "stats", "streak", "how far")) {
            StringBuilder sb = new StringBuilder("Here's your snapshot, " + first + ":\n\n")
                    .append("• ").append(dash.lessonsCompleted()).append(" lessons completed (").append(dash.minutesLearned()).append(" minutes)\n")
                    .append("• ").append(dash.completedCourses()).append(" of ").append(dash.enrolledCourses()).append(" courses finished\n")
                    .append("• ").append(dash.streakDays()).append("-day streak 🔥\n");
            if (!dash.continueLearning().isEmpty()) {
                var c = dash.continueLearning().get(0);
                sb.append("\nUp next: **").append(c.nextLessonTitle() == null ? c.course().title() : c.nextLessonTitle())
                        .append("** in ").append(c.course().title()).append(" (").append(c.progressPercent()).append("% done).");
            }
            sb.append("\n\n").append(type.charAt(3) == 'J'
                    ? "Tip for you: set a concrete weekly target — you thrive on checking things off."
                    : "Tip for you: keep sessions short and varied — momentum beats marathons for your type.");
            return new Reply(sb.toString(), List.of("What should I learn next?", "I'm feeling unmotivated"));
        }
        if (matches(q, "study", "how should i learn", "tips", "learn better", "focus", "concentrat", "memor")) {
            StringBuilder sb = new StringBuilder("Study tips tuned for an " + type + ":\n");
            p.studyTips().forEach(t -> sb.append("\n• ").append(t));
            sb.append("\n\nYour best-fit lesson formats: ")
              .append(String.join(", ", p.preferredFormats().stream().map(f -> f.name().toLowerCase()).toList())).append('.');
            return new Reply(sb.toString(), List.of("What are my strengths?", "What should I learn next?"));
        }
        if (matches(q, "strength", "weakness", "challenge", "good at", "struggle")) {
            return new Reply("As " + p.nickname() + ", your learning strengths are:\n"
                    + bullets(p.strengths()) + "\n\nWatch out for:\n" + bullets(p.challenges()),
                    List.of("How should I study?", "Tell me about my type"));
        }
        if (matches(q, "my type", "personality", "who am i", "about me", "mbti", type.toLowerCase())) {
            return new Reply("You're an **" + type + " — " + p.nickname() + "**. " + p.summary()
                    + "\n\nLearning style: " + p.learningStyle()
                    + "\n\nYour scores: " + scoreLine(user)
                    + "\n\nYou can retake the quiz anytime from your profile.",
                    List.of("What are my strengths?", "How should I study?"));
        }
        if (matches(q, "motivat", "bored", "stuck", "tired", "give up", "lazy", "procrastinat", "overwhelm")) {
            String msg = switch (type.substring(1, 3)) {
                case "NT" -> "Reframe the next lesson as a puzzle to crack. Set yourself a challenge: finish it and explain the 'why' behind it in one sentence.";
                case "NF" -> "Remember why you started — who will benefit when you master this? Pick one lesson that connects to that purpose and do just that one.";
                case "ST" -> "Shrink the task: open your next lesson and commit to only 10 minutes. Concrete, finishable steps rebuild momentum fast.";
                default -> "Learning is easier together — tell me what you just learned, or invite a friend to take the course with you. Celebrate every lesson you tick off!";
            };
            return new Reply("That happens to everyone, " + first + ". " + msg
                    + (type.charAt(3) == 'P' ? " And it's fine to switch to a different course for a bit — variety keeps you engaged." : ""),
                    List.of("How am I doing?", "What should I learn next?"));
        }
        if (matches(q, "what is mbti", "myers", "16 types", "why does personality")) {
            return new Reply("MBTI (Myers-Briggs Type Indicator) describes preferences on four scales: where you draw energy (E/I), "
                    + "how you take in information (S/N), how you decide (T/F) and how you structure your life (J/P). "
                    + "PersonaLearn uses yours to pick lesson formats, pace and courses that fit how you naturally learn.",
                    defaults);
        }
        if (matches(q, "thank", "thanks", "awesome", "great")) {
            return new Reply("Anytime, " + first + "! Keep that momentum going. 🚀", defaults);
        }
        return new Reply("Good question! I'm best at helping with your learning journey here — I can recommend courses, "
                + "share study strategies for your " + type + " personality, review your progress, or help when you feel stuck. "
                + "(Connect an AI key on the server for open-ended tutoring on any topic.)", defaults);
    }

    private boolean matches(String q, String... words) {
        for (String w : words) if (q.contains(w)) return true;
        return false;
    }

    private String bullets(List<String> items) {
        StringBuilder sb = new StringBuilder();
        items.forEach(i -> sb.append("\n• ").append(i));
        return sb.toString();
    }

    private String scoreLine(User u) {
        if (u.getScoreE() == null) return "not available";
        return pole(u.getScoreE(), "Extraversion", "Introversion") + ", "
                + pole(u.getScoreN(), "Intuition", "Sensing") + ", "
                + pole(u.getScoreT(), "Thinking", "Feeling") + ", "
                + pole(u.getScoreJ(), "Judging", "Perceiving");
    }

    private String pole(int v, String a, String b) {
        return v >= 50 ? a + " " + v + "%" : b + " " + (100 - v) + "%";
    }

    // ------------------------------------------------------------------ Claude-powered tutor

    private Reply askClaude(User user, DashboardDto dash, String text) {
        try {
            StringBuilder system = new StringBuilder(
                    "You are Persona, a warm, concise AI learning companion inside PersonaLearn, an MBTI-based LMS. "
                    + "Tailor explanations, examples and study advice to the learner's personality type. "
                    + "Keep replies under 180 words, use short paragraphs or bullets, and use **bold** sparingly.\n\n");
            system.append("Learner: ").append(user.getName()).append('\n');
            if (user.getMbtiType() != null) {
                var p = mbti.profile(user.getMbtiType());
                system.append("MBTI: ").append(p.type()).append(" (").append(p.nickname()).append(") – ").append(p.learningStyle()).append('\n')
                      .append("Scores: ").append(scoreLine(user)).append('\n')
                      .append("Preferred formats: ").append(p.preferredFormats()).append('\n');
            } else {
                system.append("MBTI: unknown – encourage them to take the quiz.\n");
            }
            system.append("Progress: ").append(dash.lessonsCompleted()).append(" lessons, ")
                  .append(dash.completedCourses()).append('/').append(dash.enrolledCourses()).append(" courses complete, streak ")
                  .append(dash.streakDays()).append(" days.\n");
            dash.continueLearning().forEach(c -> system.append("In progress: ").append(c.course().title())
                    .append(" (").append(c.progressPercent()).append("%)\n"));
            dash.recommendations().forEach(r -> system.append("Recommended: ").append(r.course().title())
                    .append(" (").append(r.matchPercent()).append("% match)\n"));

            List<Map<String, String>> convo = new ArrayList<>();
            List<ChatMessage> recent = new ArrayList<>(messages.findTop50ByUserIdOrderByCreatedAtDesc(user.getId()));
            Collections.reverse(recent);
            for (ChatMessage m : recent.subList(Math.max(0, recent.size() - 12), recent.size())) {
                String role = m.getSender().equals("user") ? "user" : "assistant";
                if (!convo.isEmpty() && convo.get(convo.size() - 1).get("role").equals(role)) continue;
                if (convo.isEmpty() && role.equals("assistant")) continue;
                convo.add(Map.of("role", role, "content", m.getContent()));
            }
            if (convo.isEmpty() || !convo.get(convo.size() - 1).get("role").equals("user")) {
                convo.add(Map.of("role", "user", "content", text));
            }

            String body = json.writeValueAsString(Map.of(
                    "model", model, "max_tokens", 600, "system", system.toString(), "messages", convo));
            HttpRequest req = HttpRequest.newBuilder(URI.create("https://api.anthropic.com/v1/messages"))
                    .timeout(Duration.ofSeconds(45))
                    .header("x-api-key", apiKey)
                    .header("anthropic-version", "2023-06-01")
                    .header("content-type", "application/json")
                    .POST(HttpRequest.BodyPublishers.ofString(body)).build();
            HttpResponse<String> res = http.send(req, HttpResponse.BodyHandlers.ofString());
            if (res.statusCode() != 200) {
                log.warn("AI provider returned {}: {}", res.statusCode(), res.body());
                return null;
            }
            JsonNode root = json.readTree(res.body());
            StringBuilder out = new StringBuilder();
            root.path("content").forEach(n -> { if ("text".equals(n.path("type").asText())) out.append(n.path("text").asText()); });
            if (out.isEmpty()) return null;
            return new Reply(out.toString().trim(), List.of("What should I learn next?", "How should I study?", "How am I doing?"));
        } catch (Exception e) {
            log.warn("AI chat failed, falling back to built-in tutor: {}", e.getMessage());
            return null;
        }
    }
}
